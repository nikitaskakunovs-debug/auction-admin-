/** Возврат после входа.
 *
 *  Человек, которого форма входа выбросила на главную, к карточке лота уже
 *  не вернётся — он потерян вместе с корзиной. Поэтому каждая кнопка «Ienākt»
 *  несёт адрес страницы, с которой пришли, а форма после входа возвращает
 *  на него.
 *
 *  Адрес принимаем только внутренний: «/login?next=https://evil.lv» и
 *  «//evil.lv» — это открытый редирект, готовая площадка для фишинга под
 *  нашим доменом. Всё, что не начинается с одиночного «/», превращается
 *  в главную.
 */
export function safeNext(raw: string | null | undefined): string {
  return raw && /^\/(?!\/)/.test(raw) ? raw : "/";
}

/** Ссылка на вход с возвратом на указанную страницу. */
export function loginHref(path: string): string {
  return `/login?next=${encodeURIComponent(safeNext(path))}`;
}
